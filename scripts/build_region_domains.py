#!/usr/bin/env python3
"""Builds the frontend's region domain tables from the boundary files the
region tags were joined against (`make region-domains`).

Writes two committed files, sorted and deterministic, so the frontend build
never needs data/:

  * src/registry/region-codes.ts — the small closed domains the Area filter
    and `where` validate against eagerly: STATE_CODES, BA_CODES (the EIA BA
    polygons' `abbrev` plus every EIA-860 `ba_code`, since EIA plants carry
    four codes the polygons do not), COUNTRY_CODES (countries' `iso_a3` plus
    the admin-1 table's parents) and STATE_TO_ADMIN1 (US state code → its
    admin-1 code in scripts/admin1_codes.csv, matched by name).
  * src/registry/region-labels.json — a display label for every code of all
    seven kinds (states, counties, ba, nerc, retail, countries, admin1),
    loaded lazily by the picker. Region names are data and stay untranslated.

Inputs: data/build/{us_states,eia_ba,nerc_regions,retail_territories,
countries}.gpkg, data/build/county_boundaries.geojson,
data/build/generator_eia.csv, scripts/admin1_codes.csv, and the NERC bucket
labels in src/colors/buckets.ts. Counties, admin-1 and retail are validated by
pattern in the frontend (src/registry/field-schema.ts);
scripts/test_region_domains.py holds the committed labels to those patterns.

    venv/bin/python scripts/build_region_domains.py
"""
from __future__ import annotations

import csv
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUILD = ROOT / "data" / "build"
ADMIN1_CSV = ROOT / "scripts" / "admin1_codes.csv"
BUCKETS_TS = ROOT / "src" / "colors" / "buckets.ts"
CODES_TS = ROOT / "src" / "registry" / "region-codes.ts"
LABELS_JSON = ROOT / "src" / "registry" / "region-labels.json"

GENERATED = "generated by scripts/build_region_domains.py; run `make region-domains`, never edit by hand"

# Territories and DC carry no county-equivalent suffix.
NO_COUNTY_SUFFIX = {"AK", "DC", "PR", "GU", "VI", "AS", "MP"}


def county_label(geoid: str, name: str, st: str) -> str:
    """'Harris County, TX'; Louisiana parishes, independent cities (county
    FIPS 500+), Connecticut planning regions and the territories by their own
    names, so two same-named units in a state stay distinct."""
    if st == "LA":
        kind = " Parish"
    elif st == "CT" and geoid.startswith("091"):
        kind = " Planning Region"
    elif int(geoid[2:]) >= 500:
        kind = "" if name.endswith("City") else " city"
    elif st in NO_COUNTY_SUFFIX:
        kind = ""
    else:
        kind = " County"
    return f"{name}{kind}, {st}"


def nerc_labels() -> dict[str, str]:
    block = BUCKETS_TS.read_text().split("export const NERC_BUCKETS", 1)[1].split("];", 1)[0]
    return dict(re.findall(r'id:\s*"([^"]+)".*?label:\s*"([^"]+)"', block))


def main() -> int:
    import pyogrio  # geo dependency stays out of module scope

    def rows(name, cols):
        df = pyogrio.read_dataframe(BUILD / name, columns=cols, read_geometry=False)
        return df[cols].astype(str).values.tolist()

    states = {code: name for _, code, name in rows("us_states.gpkg", ["geoid", "stusps", "name"])}
    counties = {g: county_label(g, n, s) for g, n, s in rows("county_boundaries.geojson", ["GEOID", "NAME", "STUSPS"])}
    ba = {code: name for code, name in rows("eia_ba.gpkg", ["abbrev", "name"])}
    with open(BUILD / "generator_eia.csv", newline="") as f:
        for r in csv.DictReader(f):
            code = r["ba_code"].strip()
            if code:
                ba.setdefault(code, code)
    retail = {i: f"{n} ({s})" for i, n, s in rows("retail_territories.gpkg", ["id", "name", "state"])}
    countries = {code: name for code, name in rows("countries.gpkg", ["iso_a3", "name"])}

    with open(ADMIN1_CSV, newline="") as f:
        admin1_rows = list(csv.DictReader(f))
    admin1 = {r["code"]: [r["name"], r["iso3"]] for r in admin1_rows}
    for r in admin1_rows:
        countries.setdefault(r["iso3"], r["iso3"])
    us_by_name = {r["name"]: r["code"] for r in admin1_rows if r["iso3"] == "USA" and r["current"] == "1"}
    missing = sorted(n for n in states.values() if n not in us_by_name)
    if missing or len(us_by_name) != len(states):
        print(f"ERROR: US states and admin-1 USA rows do not match 1:1 by name (unmatched: {missing})", file=sys.stderr)
        return 1
    state_to_admin1 = {code: us_by_name[name] for code, name in states.items()}

    nerc = nerc_labels()
    labels = {
        "_generated": GENERATED,
        "states": states, "counties": counties, "ba": ba, "nerc": nerc,
        "retail": retail, "countries": countries, "admin1": admin1,
    }
    LABELS_JSON.write_text(json.dumps(labels, sort_keys=True, ensure_ascii=False, separators=(",", ":")) + "\n")

    def arr(name, codes):
        body = ",".join(json.dumps(c) for c in sorted(codes))
        return f"export const {name}: readonly string[] = [{body}];\n"

    mapping = ",".join(f"{json.dumps(k)}:{json.dumps(v)}" for k, v in sorted(state_to_admin1.items()))
    CODES_TS.write_text(
        f"// Region code domains — {GENERATED}.\n"
        "// The small closed domains the region fields validate against (see\n"
        "// src/registry/field-schema.ts); the large ones (counties, admin-1, retail)\n"
        "// validate by pattern, and every label lives in the lazy region-labels.json.\n"
        "// Imports nothing.\n\n"
        + arr("STATE_CODES", states)
        + arr("BA_CODES", ba)
        + arr("COUNTRY_CODES", countries)
        + f"export const STATE_TO_ADMIN1: Readonly<Record<string, string>> = {{{mapping}}};\n"
    )
    print(f"[done] {CODES_TS.relative_to(ROOT)}: {len(states)} states, {len(ba)} BAs, {len(countries)} countries")
    print(f"[done] {LABELS_JSON.relative_to(ROOT)}: {len(counties)} counties, {len(retail)} retail, "
          f"{len(admin1)} admin-1, {len(nerc)} NERC")
    return 0


if __name__ == "__main__":
    sys.exit(main())
